const skillCatalogUpdatedAt = "2026-07-26T00:00:00.000Z";

function vendorArtifact(skillId: string, version: string) {
  const artifact = vendorSkillManifest.artifacts.find(
    (candidate) =>
      candidate.skillId === skillId && candidate.version === version,
  );
  if (!artifact) {
    throw new Error(`Vendor Skill artifact is missing: ${skillId}@${version}`);
  }
  return {
    digest: artifact.digest,
    endpoint: `tali+postgresql://skill-artifacts/${skillId}/${version}`,
  };
}

function skillInformation(
  author: string,
  problemStatement: string,
  useCases: string[],
  usageGuide: string,
) {
  return {
    author,
    problemStatement,
    updatedAt: skillCatalogUpdatedAt,
    useCases,
    usageGuide,
  };
}


#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { parseAllDocuments } from "yaml";
import { parse as parseToml } from "smol-toml";
import { materializeBootstrapSecrets } from "./testing/helm-bootstrap-fixture.mjs";

const developmentProjects = JSON.parse(
  readFileSync("config/development-projects.json", "utf8"),
);
const expectedProjects = [
  { departmentId: "dep1", name: "proj1", keycloakGroup: "proj1" },
  { departmentId: "dep1", name: "Isolation 1", keycloakGroup: "isolation-1" },
];
if (JSON.stringify(developmentProjects) !== JSON.stringify(expectedProjects)) {
  throw new Error(
    "Development defaults must declare Project names in dep1 without overriding generated IDs.",
  );
}

const rendered = execFileSync(
  "helm",
  [
    "template",
    "tali-relay",
    "charts/tali-relay",
    "--namespace",
    "tali-development-defaults",
    "--kube-version",
    "1.29.0",
    "--values",
    "charts/tali-relay/values-dev.yaml",
    "--set-string",
    "control.publicUrls[0]=http://localhost:38080",
    "--set",
    "keycloak.enabled=true",
    "--set-string",
    "keycloak.publicUrl=http://keycloak.localhost:8180",
  ],
  { encoding: "utf8" },
);
const objects = parseAllDocuments(rendered, { uniqueKeys: false })
  .map((document) => {
    if (document.errors.length) throw document.errors[0];
    return document.toJS();
  })
  .filter((object) => object && typeof object === "object");
if (objects.some(object => object.kind === "Secret" && object.metadata.name !== "tali-relay-worker-config")) {
  throw new Error("Development credentials must be generated by the Job, not rendered into Helm manifests.");
}
const generated = materializeBootstrapSecrets(objects);
const secret = { stringData: Object.assign({}, ...generated.filter((object) => object.kind === "Secret").map((object) => object.stringData ?? {})) };
const credentials = [];
for (const key of [
  "keycloak-admin-password",
  "keycloak-test-user-password",
  "litellm-ui-password",
]) {
  if (!/^[a-f0-9]{64}$/.test(secret.stringData?.[key] ?? "")) {
    throw new Error(`${key} must use an independently generated credential.`);
  }
  credentials.push(secret.stringData[key]);
}
const administrator = parseToml(secret.stringData["control.toml"]).auth.local.initial_platform_administrator_password;
credentials.push(administrator);
if (!/^[a-f0-9]{64}$/.test(administrator) || new Set(credentials).size !== credentials.length) {
  throw new Error("The local administrator and component credentials must be independently generated.");
}

const realmConfig = objects.find(
  (object) => object.kind === "ConfigMap"
    && object.metadata?.name === "tali-relay-keycloak-realm",
);
if (!realmConfig) throw new Error("The development Keycloak realm was not rendered.");
const realm = JSON.parse(realmConfig.data["tali-realm.json"]);
if (!realm.users?.length) throw new Error("The Keycloak realm has no test users.");
for (const user of realm.users) {
  const passwords = (user.credentials ?? [])
    .filter(({ type }) => type === "password")
    .map(({ value }) => value);
  if (
    passwords.length !== 1
    || passwords[0] !== "${TALI_KEYCLOAK_TEST_USER_PASSWORD}"
  ) {
    throw new Error(
      `Keycloak test user ${user.username} does not use the shared development password Secret.`,
    );
  }
}
const taliGroup = realm.groups?.find(({ name }) => name === "tali");
const departmentProjects = taliGroup?.subGroups
  ?.find(({ name }) => name === "d")?.subGroups
  ?.find(({ name }) => name === "dep1")?.subGroups
  ?.find(({ name }) => name === "p")?.subGroups
  ?.map(({ name }) => name) ?? [];
for (const { keycloakGroup: groupName } of expectedProjects) {
  if (!departmentProjects.includes(groupName)) {
    throw new Error(`The Keycloak realm is missing Project group ${groupName}.`);
  }
}

console.log(
  `Validated ${developmentProjects.length} development Projects, independent credentials and ${realm.users.length} Secret-backed Keycloak users.`,
);
